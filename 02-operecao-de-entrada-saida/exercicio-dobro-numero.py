# Faça um programa que peça um nuemro ao input
# E mostre o dobro desse numero

# Entrada de dados 
numero = int(input("Digite um numero: "))
mult = int(input("Digite numero para a multiplicação: "))
 
# Processamento de dados
arit = numero * mult

 # Saida de informações 
print(f"O resultado do seu numero é: {arit}")