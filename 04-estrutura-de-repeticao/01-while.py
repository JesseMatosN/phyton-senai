# Define o valor inicial do contador
contador = 1

# Enquanto o contador for menor que ou igual a 5
while contador <= 5:

    # Mostra o valor atual do contador
    print(f"contador agora é: {contador}")

    # Aumenta o contador em 1
    contador = contador + 1

# Mostra uma menssagem quando o whule termina
print("contador chegou a 6. while termino!")
